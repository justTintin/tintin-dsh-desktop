const standard = readFileSync(join(standardDir, 'agent.cordis.yml'), 'utf8')
const PERSONA_BLOCK = `- id: persona
  name: '@deepseek-ai/dsh-persona'
  config:
    suffix: Your working directory is {{cwd}}.
    prefix: >-
      You are a coding agent powered by the {{model}} model.`

if (!standard.includes(PERSONA_BLOCK)) {
  console.error('standard persona block not found verbatim — preset template drifted; re-verify before rebuilding')
  process.exit(1)
}

for (const role of ROLES) {
  const dir = join(outRoot, role.id)
  mkdirSync(dir, { recursive: true })
  const header = `# TinTin role preset (generated by scripts/build-tintin-presets.mjs).\n# Base: @deepseek-ai/dsh-agent-presets/presets/standard/agent.cordis.yml\n# verbatim; ONLY the persona block differs (WP-5c: 工具沿用，人设按角色重写).\n# Rebuild after a harness upgrade refreshes the base — review the diff.\n\n`
  const composition = standard.replace(PERSONA_BLOCK, `- id: persona
  name: '@deepseek-ai/dsh-persona'
  config:
    suffix: Your working directory is {{cwd}}.
    prefix: >-
      ${role.persona}`)
  writeFileSync(join(dir, 'agent.cordis.yml'), header + composition, 'utf8')
  writeFileSync(join(dir, 'preset.yml'), `name: ${role.name}\ndescription: ${role.description}\norder: ${role.order}\n`, 'utf8')
  console.log(`built ${role.id} (${role.name})`)
}
console.log('done: 5 presets in packages/tintin-bundle/presets/')
